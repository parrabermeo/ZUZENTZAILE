export function getTagDisplay(tag: string, lang: Language): { label: string; classes: string } {
  const preset = PRESET_TAGS.find((p) => p.id === tag);
  if (preset) {
    return { label: preset.label[lang], classes: preset.badgeClasses };
  }
  return {
    label: tag,
    classes: 'bg-slate-100 text-slate-700 border-slate-200',
  };
}

